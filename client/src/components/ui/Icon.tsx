export type IconName = keyof typeof library;

type IconComponentProps = IconProps & {
  name: IconName;
};

/**
 * Render a Lucide icon by name with consistent sizing/stroke.
 *
 * @example
 *   <Icon name="CheckCircle" className="text-success" size={20} />
 */
export function Icon({
  name,
  size = 20,
  strokeWidth = 2,
  className,
  title,
  ...props
}: IconComponentProps) {
  const Component = library[name] as LucideIcon;
  const a11yProps = title
    ? ({ role: "img", "aria-label": title } as const)
    : ({ "aria-hidden": true } as const);
  return (
    <Component
      size={size}
      strokeWidth={strokeWidth}
      className={cn("inline-block", className)}
      {...a11yProps}
      {...props}
    />
  );
}

export const IconLib = library as unknown as Record<IconName, LucideIcon>;
